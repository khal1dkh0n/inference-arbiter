class RecordingJudge:
    def __init__(self, status: str = "pass") -> None:
        self.status = status
        self.cases: list[dict] = []

    def judge(self, case, answer) -> Grade:
        self.cases.append(case)
        return Grade(status=self.status, reason="judged", match_type="rubric", judge_tier="mid",
                     judge_model="mid-model", judge_cost_usd=0.01, detail={"criteria": []})


ANSWER_THEN_ALTERNATIVE = "The query returns **`0`**.\n\nWith NOT EXISTS instead it returns **`3`**."
