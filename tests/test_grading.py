def test_exact_expected_present_needs_a_standalone_form():
    assert exact_expected_present(FENCED_THEN_ALTERNATIVE, "1,10,100,9") is True
    assert exact_expected_present("The symbol is **W**, from **wolfram**.", "W") is True
    assert exact_expected_present("Answer: W\nIt comes from wolfram.", "W") is True
    # A substring is not a stated answer: 'w' is inside 'wolfram' and 'tungsten was'.
    assert exact_expected_present("Tungsten was named wolfram.", "W") is False
    assert exact_expected_present("[1] [1, 2] [3] [1, 2, 4]", "[1, 2, 4] [1, 2, 4] [3] [1, 2, 4]") is False


def test_deterministic_fail_reports_whether_the_expected_value_is_present():
    assert grade_numeric(ANSWER_THEN_ALTERNATIVE, 0, 0).detail["expected_present"] is True
    assert grade_numeric("180", 270, 0).detail["expected_present"] is False
    assert grade_exact(FENCED_THEN_ALTERNATIVE, "1,10,100,9").detail["expected_present"] is True
    assert grade_exact("bdfhca", "bdfheb").detail["expected_present"] is False


