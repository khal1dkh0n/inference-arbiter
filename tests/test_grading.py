def exact_case(expected_answer: str) -> dict:
    return {"id": "X-01", "question": "q?", "expected_answer": expected_answer, "match": {"type": "exact"}}


def numeric_case(value, tolerance) -> dict:
    return {
        "id": "N-01",
        "question": "q?",
        "expected_answer": str(value),
        "match": {"type": "numeric", "value": value, "tolerance": tolerance},
    }


def verdict_json(met_flags: list[bool], passed: bool | None = None, rationale: str = "judged") -> str:
    overall = all(met_flags) if passed is None else passed
    return json.dumps(
        {
            "criteria": [
                {"index": number, "met": met, "note": "n"} for number, met in enumerate(met_flags, start=1)
            ],
            "rationale": rationale,
            "passed": overall,
        }
    )


def make_judge(*results) -> tuple[LlmRubricJudge, FakeClient]:
    config = make_config()
    client = FakeClient()
    client.script("mid-model", *results)
    return LlmRubricJudge(client, config.tiers["mid"], "mid"), client


