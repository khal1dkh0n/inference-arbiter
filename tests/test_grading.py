class AbstentionJudge:
    """Says 'abstained' (criterion met) when the answer contains 'do not contain'."""

    def __init__(self, raises: bool = False, ungraded: bool = False) -> None:
        self.raises = raises
        self.ungraded = ungraded
        self.cases: list[dict] = []

    def judge(self, case, answer) -> Grade:
        self.cases.append(case)
        if self.raises:
            raise RuntimeError("judge down")
        if self.ungraded:
            return Grade(status=GRADE_UNGRADED, reason="judge call failed", match_type="rubric")
        status = GRADE_PASS if "do not contain" in answer else GRADE_FAIL
        return Grade(status=status, reason="judged", match_type="rubric", judge_tier="mid",
                     judge_model="judge-model", judge_cost_usd=0.002, judge_latency_ms=40.0)


